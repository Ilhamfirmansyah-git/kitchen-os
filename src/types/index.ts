/* ---------------------------------------------------------------------------
 * Kitchen OS domain types
 * ------------------------------------------------------------------------- */

export type Difficulty = "easy" | "medium" | "hard";

export type RecipeCategory =
  | "Indonesian"
  | "Japanese"
  | "Korean"
  | "Chinese"
  | "Western"
  | "Italian"
  | "Breakfast"
  | "Dessert"
  | "Drinks"
  | "Baking";

export type MealType = "breakfast" | "lunch" | "dinner" | "snack" | "dessert" | "drink";

export type MainIngredient =
  | "chicken"
  | "beef"
  | "pork"
  | "seafood"
  | "egg"
  | "tofu"
  | "vegetables"
  | "rice"
  | "noodles"
  | "pasta"
  | "flour"
  | "fruit"
  | "dairy"
  | "coffee";

/** Units are stored in metric/kitchen units and converted for display. */
export type Unit =
  | "g"
  | "kg"
  | "ml"
  | "l"
  | "tsp"
  | "tbsp"
  | "cup"
  | "pcs"
  | "clove"
  | "slice"
  | "stalk"
  | "pinch"
  | "to taste";

export interface Ingredient {
  id: string;
  name: string;
  quantity: number;
  unit: Unit;
  notes?: string;
  /** Optional ingredients are shown but not required. */
  optional?: boolean;
}

export interface CookingStep {
  id: string;
  order: number;
  /**
   * Instruction text. Temperatures are written as tokens like `{t:180}` (°C)
   * so they can be rendered in the user's preferred unit.
   */
  instruction: string;
  /** Short title shown above the instruction in Cooking Mode. */
  title?: string;
  durationSeconds?: number;
  ingredientIds?: string[];
  image?: string;
  tip?: string;
}

export interface Recipe {
  id: string;
  slug: string;
  name: string;
  description: string;
  /** Optional photo path or URL. Falls back to generated artwork. */
  image?: string;
  cuisine: string;
  category: RecipeCategory;
  mealTypes: MealType[];
  mainIngredient: MainIngredient;
  difficulty: Difficulty;
  preparationMinutes: number;
  cookingMinutes: number;
  defaultServings: number;
  ingredients: Ingredient[];
  equipment: string[];
  steps: CookingStep[];
  /** YouTube video id of a related tutorial, if one is known. */
  videoId?: string;
  tags?: string[];
  /**
   * Nutrition is intentionally optional and absent from the bundled sample
   * data: it is only shown when real, sourced values are provided.
   */
  nutrition?: { calories: number; source: string; perServing: true };
  /** Accent hue used for the generated artwork. */
  hue: number;
}

export interface Video {
  id: string; // YouTube video id
  title: string;
  channel?: string;
  category: VideoCategory;
  description: string;
  recipeSlug?: string;
  featured?: boolean;
}

export type VideoCategory = "Techniques" | "Indonesian" | "Korean" | "Japanese" | "Breakfast" | "Italian" | "Baking";

/* ---------------- Persistence models ---------------- */

export type TimerStatus = "idle" | "running" | "paused" | "done";

export interface KitchenTimer {
  id: string;
  label: string;
  durationMs: number;
  status: TimerStatus;
  /** Epoch ms when the timer reaches zero. Only meaningful while running. */
  endsAt: number | null;
  /** Remaining ms while idle/paused. */
  remainingMs: number;
  createdAt: number;
  /** Epoch ms the timer hit zero. */
  finishedAt: number | null;
  /** True once the user has dismissed the alarm. */
  acknowledged: boolean;
  source?: { recipeSlug: string; stepId: string };
}

export interface CookingSession {
  recipeSlug: string;
  stepIndex: number;
  servings: number;
  startedAt: number;
  /** Accumulated elapsed ms, excluding the currently running stretch. */
  elapsedMs: number;
  /** Epoch ms of the start of the current running stretch; null when paused. */
  runningSince: number | null;
  updatedAt: number;
}

export interface HistoryEntry {
  slug: string;
  at: number;
}

export type ClockFormat = "24h" | "12h";
export type TemperatureUnit = "C" | "F";
export type MeasurementSystem = "metric" | "us";
export type ThemeName = "dark" | "midnight";

export interface Settings {
  theme: ThemeName;
  soundEffects: boolean;
  alarmVolume: number; // 0..1
  clockFormat: ClockFormat;
  temperatureUnit: TemperatureUnit;
  measurement: MeasurementSystem;
  reduceMotion: boolean;
  debugNavigation: boolean;
  userName: string;
}

export interface ChatMessage {
  id: string;
  role: "user" | "assistant";
  content: string;
  at: number;
  /** "ai" = generated by the configured model; "demo" = pre-written demo content. */
  source?: "ai" | "demo";
  error?: boolean;
  /** Kitchen OS recipes referenced by the answer (rendered as buttons). */
  recipeSlugs?: string[];
}

export interface Conversation {
  id: string;
  title: string;
  messages: ChatMessage[];
  updatedAt: number;
}
